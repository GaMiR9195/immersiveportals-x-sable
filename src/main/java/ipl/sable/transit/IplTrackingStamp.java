package ipl.sable.transit;

/**
 * Метка часов трекинга Sable для серверного тика (реализуется миксином на
 * {@code SubLevelTrackingSystem}).
 *
 * <p>Sable штампует снимки поз счётчиком {@code interpolationTick}, который у каждого уровня
 * свой. Чтобы клиент мог бесшовно продолжить интерполяцию корабля, перешедшего в другое
 * измерение, сервер передаёт разницу меток обоих уровней для ОДНОГО и того же серверного тика.
 */
public interface IplTrackingStamp {

    /** Метка, которой этот уровень штампует (или проштампует) снимки серверного тика {@code serverTick}. */
    int ipl$stampFor(int serverTick);
}
